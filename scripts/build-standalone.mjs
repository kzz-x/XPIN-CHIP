import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const assets=path.join(root,'dist','assets');
const names=await readdir(assets);
const jsNames=names.filter(n=>n.endsWith('.js')),cssNames=names.filter(n=>n.endsWith('.css'));
if(jsNames.length!==1||cssNames.length!==1)throw new Error('Expected exactly one JS and CSS bundle');
let html=await readFile(path.join(root,'dist','index.html'),'utf8');
const js=(await readFile(path.join(assets,jsNames[0]),'utf8')).replace(/<\/script/gi,'<\\/script');
const css=(await readFile(path.join(assets,cssNames[0]),'utf8')).replace(/<\/style/gi,'<\\/style');
const script=/<script\b(?=[^>]*\btype="module")(?=[^>]*\bsrc="[^"]+")[^>]*>\s*<\/script>/i;
const style=/<link\b(?=[^>]*\brel="stylesheet")(?=[^>]*\bhref="[^"]+")[^>]*>/i;
if(!script.test(html)||!style.test(html))throw new Error('Missing Vite assets');
html=html.replace(script,()=>'<script type="module">\n'+js+'\n</script>').replace(style,()=>'<style>\n'+css+'\n</style>').replace(/\r\n?/g,'\n');
if(/(?:src|href)="[^"\n]*assets\//.test(html))throw new Error('External asset left in HTML');
const target=path.join(root,'XPIN-CHIP-Standalone.html');
await writeFile(target,html);
console.log(`Wrote fully offline HTML: ${Buffer.byteLength(html).toLocaleString()} bytes`);
